CREATE COLLATION rain_biz_code (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE mxsm_allocation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_code varchar(128) NOT NULL,
    biz_key text COLLATE rain_biz_code GENERATED ALWAYS AS (rtrim(biz_code, ' ')) STORED UNIQUE,
    max_id bigint NOT NULL DEFAULT 1,
    step integer NOT NULL CHECK (step > 0),
    description varchar(255) DEFAULT '',
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mxsm_snowfalke_node (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_name bigint NOT NULL,
    port integer NOT NULL DEFAULT 1,
    deploy_env_type varchar(16) DEFAULT 'ACTUAL' CHECK (deploy_env_type IN ('ACTUAL', 'CONTAINER')),
    description varchar(255) DEFAULT '',
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (host_name, port)
);
